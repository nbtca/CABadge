"""Generate the eight native 64px battle sprites from checked-in PNGs."""
from pathlib import Path
import hashlib
import json
from PIL import Image

root = Path(__file__).resolve().parent
folder = root/'ui/pokemon_sprites'
manifest = json.loads((folder/'sources.json').read_text(encoding='utf-8'))
out = ['/* Generated by generate_pokemon_assets.py; see pokemon_sprites/CREDITS.md. */\n#include "pokemon_art.h"\n']
for index, dex in enumerate((1, 4, 7, 25)):
    for view in ('front', 'back'):
        path = folder/f'{dex}_{view}.png'
        assert hashlib.sha256(path.read_bytes()).hexdigest() == manifest[path.name]['sha256']
        image = Image.open(path).convert('RGBA')
        assert image.size == (64, 64)
        assert image.getchannel('A').getextrema() == (0, 255)
        data = image.tobytes('raw', 'BGRA')
        name = f'pk_{index}_{view}'
        out.append(f'static const uint8_t {name}_data[]={{'+','.join(map(str, data))+'};\n')
        out.append(f'static const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_ARGB8888,.w=64,.h=64,.stride=256}},.data_size=sizeof({name}_data),.data={name}_data}};\n')
out.append('const lv_image_dsc_t *const pokemon_front[4]={'+','.join(f'&pk_{i}_front' for i in range(4))+'};\n')
out.append('const lv_image_dsc_t *const pokemon_back[4]={'+','.join(f'&pk_{i}_back' for i in range(4))+'};\n')
(root/'ui/pokemon_art.c').write_text(''.join(out), encoding='utf-8')
print('PASS eight pinned 64x64 BGRA sprites, 131072 bytes in Flash')
